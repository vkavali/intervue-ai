export function getTemplatesByDepartment(department: string): TemplatePreset[] {
  return TEMPLATE_LIBRARY.filter(t => t.department === department);
}

export function getTemplateById(id: string): TemplatePreset | undefined {
  return TEMPLATE_LIBRARY.find(t => t.id === id);
}

export function getAllDepartments(): string[] {
  return Array.from(new Set(TEMPLATE_LIBRARY.map(t => t.department)));
}
